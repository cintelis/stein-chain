#!/usr/bin/env bash
# Enforces the contributor rule in AGENTS.md: every commit in this repository is
# authored and committed by exactly one identity, and no commit message credits
# anyone or anything else.
#
#   check-identity.sh history [<rev-range>]   every commit in range (default: all of HEAD) — CI, pre-push
#   check-identity.sh ident                   the identity git is about to commit with   — pre-commit
#   check-identity.sh message <file>          a commit message file                      — commit-msg

set -euo pipefail

EXPECTED="Nick Forshteyn <nick@cintelis.ai>"

# Lines that credit another contributor, human or tool. Case-insensitive.
#   TRAILER  any "<Something>-by:" trailer (Co-authored-by, Signed-off-by,
#            Reviewed-by, Assisted-by, ...) naming anyone but EXPECTED
#   FOOTER   a line opening with "Generated with ..." / "Generated by ...",
#            optionally behind an emoji or other punctuation
TRAILER='^[[:space:]]*[[:alpha:]-]+-by:'
FOOTER='^[[:space:]]*[^[:alnum:]]*[[:space:]]*generated (with|by) '

fail=0
bad() { echo "identity: $*" >&2; fail=1; }

# Reads the message on stdin. Always call with `< <(...)`, never on the right of
# a pipe: a pipeline runs it in a subshell and the failure flag would be lost.
check_message() { # <label>
  local msg hits
  msg=$(cat)
  hits=$({
    grep -Ein "$TRAILER" <<<"$msg" | grep -vF "$EXPECTED"
    grep -Ein "$FOOTER" <<<"$msg"
  } || true)
  [ -z "$hits" ] || bad "$1: message credits another contributor:
$hits"
}

case "${1:-}" in
  history)
    range="${2:-HEAD}"
    while IFS=$'\x1f' read -r sha author committer; do
      [ "$author" = "$EXPECTED" ]    || bad "${sha:0:7}: author is '$author'"
      [ "$committer" = "$EXPECTED" ] || bad "${sha:0:7}: committer is '$committer'"
      check_message "${sha:0:7}" < <(git log -1 --format=%B "$sha")
    done < <(git log --format='%H%x1f%an <%ae>%x1f%cn <%ce>' "$range")
    ;;
  ident)
    for kind in AUTHOR COMMITTER; do
      ident=$(git var "GIT_${kind}_IDENT")   # "Name <email> <timestamp> <tz>"
      ident="${ident%>*}>"
      [ "$ident" = "$EXPECTED" ] || bad "would commit with ${kind,,} '$ident'"
    done
    ;;
  message)
    check_message "commit message" < <(grep -v '^#' "${2:?message file required}" || true)
    ;;
  *)
    echo "usage: $0 history [<rev-range>] | ident | message <file>" >&2
    exit 64
    ;;
esac

if [ "$fail" -ne 0 ]; then
  echo "identity: expected every commit to be '$EXPECTED' with no co-author or tool credit — see AGENTS.md" >&2
  exit 1
fi
